// Асинхронные языки
// Асинхронность позволяет коду выполнять задачи без блокировки основного потока. 
// Асинхронный подход основан на обработке событий, использовании обратных вызовов 
// (callbacks), промисов (promises), либо ключевых слов async/await.

// Примеры языков с развитой асинхронной моделью:

// JavaScript
// Асинхронный по природе (использует Event Loop).
// Примеры: setTimeout, промисы, async/await.

// Python
// Асинхронность через asyncio, await.
// Отлично подходит для работы с I/O (ввод/вывод).

// Ruby
// Использует гемы (например, EventMachine или async).

// Go
// Поддерживает легковесные "горутины" (goroutines) для асинхронной работы.

// Node.js
// Построен на основе асинхронной модели с использованием событий и async/await.

// Многопоточные языки
// Многопоточность позволяет одновременно выполнять несколько потоков внутри одного процесса. 
// Потоки могут работать независимо, что подходит для задач с высокой вычислительной нагрузкой.

// Примеры языков с сильной многопоточностью:

// Java
// Встроенная поддержка потоков (классы Thread, Runnable).

// C++
// Библиотеки для работы с потоками, например std::thread.

// C#
// Поддерживает многопоточность через Thread, Task, async/await.

// Rust
// Обеспечивает безопасную многопоточность с минимизацией гонок данных.

// Kotlin
// Поддерживает многопоточность через корутины (среднее между асинхронностью и потоками).

// Swift
// Использует GCD (Grand Central Dispatch) и операции для многопоточности.

// Асинхронные и многопоточные языки
// Некоторые языки поддерживают оба подхода, чтобы работать эффективно в разных ситуациях:

// C#: позволяет использовать потоки и async/await для асинхронности.
// Python: поддерживает многопоточность (через threading) и асинхронность (через asyncio).
// Go: корутины (горутины) совмещают асинхронность и параллельность.
// Rust: безопасно сочетает потоки и асинхронность.



