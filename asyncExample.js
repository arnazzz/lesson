// Что такое асинхронность в JavaScript?
// JavaScript выполняется построчно и поочерёдно (синхронно). Но иногда нужно выполнить код позже, например:
// 1. запросить данные с сервера,
// 2. дождаться ответа,
// 3. просто подождать 2 секунды.

// Для этого используются асинхронные конструкции:

// 1. setTimeout — выполнить позже

console.log("Начало");

setTimeout(() => {
    console.log("Прошло 2 секунды");
}, 2000);

console.log("Конец");

// 2. setInterval — выполнять что-то регулярно

let count = 0;

const timer = setInterval(() => {
    count++;
    console.log(`Прошла ${count} секунда`);

    if (count === 5) {
        clearInterval(timer);
        console.log("Таймер остановлен");
    }
}, 1000);

// 3. Promise — обещание результата в будущем. 
// Promise (обещание) — это объект, который обещает вернуть результат в будущем.
// Он нужен, когда:
// ты не знаешь результат сразу (например, загружаешь файл, получаешь данные с сервера),
// и тебе нужно обработать результат позже.

// Состояния Promise
// pending	        Ожидание (обещание ещё не выполнено)
// fulfilled	    Выполнено успешно (resolve)
// rejected	        Выполнено с ошибкой (reject)

const promise = new Promise((resolve, reject) => {
    const success = false;

    if (success) {
        resolve("Всё прошло хорошо");
    } else {
        reject("Что-то пошло не так");
    }
});

promise
    .then(data => console.log(data))
    .catch(error => console.error(error)); 



// 4. async / await — асинхронный код как синхронный

function getData() {
    return new Promise(resolve => {
        setTimeout(() => {
            resolve("Ответ с сервера");
        }, 2000);
    });
}

async function showData() {
    console.log("Запрашиваем данные...");
    const result = await getData();
    console.log(result); 
}

showData();

// 5. fetch() — запрос к серверу (реальное применение)

async function getUsers() {
    const response = await fetch("https://jsonplaceholder.typicode.com/users");
    const users = await response.json();
    console.log(users);
}

getUsers();


// Шпаргалка
// setTimeout	        Выполняет код один раз через заданное время
// setInterval	        Повторяет выполнение кода через интервалы
// clearInterval	    Останавливает setInterval
// Promise	            Представляет асинхронную операцию
// resolve, reject	    Завершает Promise успешно/с ошибкой
// .then()	            Обработка успешного результата
// .catch()	            Обработка ошибки
// async	            Делает функцию асинхронной
// await	            Ожидает Promise внутри async функции
// fetch()	            Запрос к серверу (API)
